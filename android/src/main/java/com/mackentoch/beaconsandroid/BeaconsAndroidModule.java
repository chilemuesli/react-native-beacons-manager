package com.mackentoch.beaconsandroid;

import android.content.Context;
import android.content.Intent;
import android.content.ServiceConnection;
import android.util.Log;

import androidx.annotation.NonNull;

import com.facebook.react.bridge.Arguments;
import com.facebook.react.bridge.Promise;
import com.facebook.react.bridge.ReactApplicationContext;
import com.facebook.react.bridge.ReadableArray;
import com.facebook.react.bridge.ReadableMap;
import com.facebook.react.bridge.WritableArray;
import com.facebook.react.bridge.WritableMap;
import com.facebook.react.module.annotations.ReactModule;

import org.altbeacon.beacon.Beacon;
import org.altbeacon.beacon.BeaconConsumer;
import org.altbeacon.beacon.BeaconManager;
import org.altbeacon.beacon.BeaconParser;
import org.altbeacon.beacon.Identifier;
import org.altbeacon.beacon.MonitorNotifier;
import org.altbeacon.beacon.RangeNotifier;
import org.altbeacon.beacon.Region;
import org.altbeacon.beacon.BeaconTransmitter;
import org.altbeacon.beacon.service.ArmaRssiFilter;
import org.altbeacon.beacon.service.RunningAverageRssiFilter;

import java.util.Collection;

/**
 * TurboModule (New Architecture). The abstract base class
 * {@link NativeBeaconsManagerSpec} is generated by codegen from
 * src/NativeBeaconsManager.ts.
 */
@ReactModule(name = BeaconsAndroidModule.NAME)
public class BeaconsAndroidModule extends NativeBeaconsManagerSpec implements BeaconConsumer {
  public static final String NAME = "BeaconsManager";
  private static final String LOG_TAG = "BeaconsAndroidModule";
  private static final String E_BEACONS = "E_BEACONS";
  private static final int RUNNING_AVG_RSSI_FILTER = 0;
  private static final int ARMA_RSSI_FILTER = 1;
  private static final String PARSER_IBEACON = "m:0-3=4c000215,i:4-19,i:20-21,i:22-23,p:24-24";

  private final Context mApplicationContext;
  private final ReactApplicationContext mReactContext;
  private BeaconManager mBeaconManager;

  public BeaconsAndroidModule(ReactApplicationContext reactContext) {
    super(reactContext);
    Log.d(LOG_TAG, "BeaconsAndroidModule - started");
    this.mReactContext = reactContext;
    this.mApplicationContext = reactContext.getApplicationContext();
  }

  @Override
  public void initialize() {
    super.initialize();
    mBeaconManager = BeaconManager.getInstanceForApplication(mApplicationContext);
    // need to bind at instantiation so that service loads
    mBeaconManager.getBeaconParsers().add(new BeaconParser().setBeaconLayout(PARSER_IBEACON));
    bindManager();
  }

  @Override
  public void invalidate() {
    if (mBeaconManager != null) {
      mBeaconManager.removeMonitorNotifier(mMonitorNotifier);
      mBeaconManager.removeRangeNotifier(mRangeNotifier);
      unbindManager();
    }
    super.invalidate();
  }

  @Override
  @NonNull
  public String getName() {
    return NAME;
  }

  private void bindManager() {
    if (!mBeaconManager.isBound(this)) {
      Log.d(LOG_TAG, "bindManager");
      mBeaconManager.bind(this);
    }
  }

  private void unbindManager() {
    if (mBeaconManager.isBound(this)) {
      Log.d(LOG_TAG, "unbindManager");
      mBeaconManager.unbind(this);
    }
  }

  /***********************************************************************************************
   * Android only
   **********************************************************************************************/
  @Override
  public void setHardwareEqualityEnforced(boolean flag) {
    Beacon.setHardwareEqualityEnforced(flag);
  }

  @Override
  public void addParser(String parser, Promise promise) {
    try {
      Log.d(LOG_TAG, "addParser: " + parser);
      unbindManager();
      mBeaconManager.getBeaconParsers().add(new BeaconParser().setBeaconLayout(parser));
      bindManager();
      promise.resolve(null);
    } catch (Exception e) {
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  @Override
  public void removeParser(String parser, Promise promise) {
    try {
      Log.d(LOG_TAG, "removeParser: " + parser);
      unbindManager();
      mBeaconManager.getBeaconParsers().remove(new BeaconParser().setBeaconLayout(parser));
      bindManager();
      promise.resolve(null);
    } catch (Exception e) {
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  @Override
  public void addParsersListToDetection(ReadableArray parsers, Promise promise) {
    try {
      unbindManager();
      for (int i = 0; i < parsers.size(); i++) {
        String parser = parsers.getString(i);
        Log.d(LOG_TAG, "addParsersListToDetection - add parser: " + parser);
        mBeaconManager.getBeaconParsers().add(new BeaconParser().setBeaconLayout(parser));
      }
      bindManager();
      promise.resolve(null);
    } catch (Exception e) {
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  @Override
  public void removeParsersListToDetection(ReadableArray parsers, Promise promise) {
    try {
      unbindManager();
      for (int i = 0; i < parsers.size(); i++) {
        String parser = parsers.getString(i);
        Log.d(LOG_TAG, "removeParsersListToDetection - remove parser: " + parser);
        mBeaconManager.getBeaconParsers().remove(new BeaconParser().setBeaconLayout(parser));
      }
      bindManager();
      promise.resolve(null);
    } catch (Exception e) {
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  @Override
  public void setBackgroundScanPeriod(double period) {
    mBeaconManager.setBackgroundScanPeriod((long) period);
  }

  @Override
  public void setBackgroundBetweenScanPeriod(double period) {
    mBeaconManager.setBackgroundBetweenScanPeriod((long) period);
  }

  @Override
  public void setForegroundScanPeriod(double period) {
    mBeaconManager.setForegroundScanPeriod((long) period);
  }

  @Override
  public void setForegroundBetweenScanPeriod(double period) {
    mBeaconManager.setForegroundBetweenScanPeriod((long) period);
  }

  @Override
  public void setRssiFilter(double filterType, double avgModifier) {
    String logMsg = "Could not set the rssi filter.";
    if ((int) filterType == RUNNING_AVG_RSSI_FILTER) {
      logMsg = "Setting filter RUNNING_AVG";
      BeaconManager.setRssiFilterImplClass(RunningAverageRssiFilter.class);
      if (avgModifier > 0) {
        RunningAverageRssiFilter.setSampleExpirationMilliseconds((long) avgModifier);
        logMsg += " with custom avg modifier";
      }
    } else if ((int) filterType == ARMA_RSSI_FILTER) {
      logMsg = "Setting filter ARMA";
      BeaconManager.setRssiFilterImplClass(ArmaRssiFilter.class);
      if (avgModifier > 0) {
        ArmaRssiFilter.setDEFAULT_ARMA_SPEED(avgModifier);
        logMsg += " with custom avg modifier";
      }
    }
    Log.d(LOG_TAG, logMsg);
  }

  @Override
  public void checkTransmissionSupported(Promise promise) {
    promise.resolve(BeaconTransmitter.checkTransmissionSupported(mReactContext));
  }

  @Override
  public void getRangedRegions(Promise promise) {
    WritableArray array = Arguments.createArray();
    for (Region region : mBeaconManager.getRangedRegions()) {
      WritableMap map = Arguments.createMap();
      map.putString("region", region.getUniqueId());
      map.putString("uuid", region.getId1() != null ? region.getId1().toString() : "");
      array.pushMap(map);
    }
    promise.resolve(array);
  }

  /***********************************************************************************************
   * iOS only (no-ops on Android)
   **********************************************************************************************/
  @Override
  public void requestAlwaysAuthorization() {}

  @Override
  public void requestWhenInUseAuthorization() {}

  @Override
  public void allowsBackgroundLocationUpdates(boolean allow) {}

  @Override
  public void getAuthorizationStatus(Promise promise) {
    // Android permissions are handled by the app.
    promise.resolve("notDetermined");
  }

  @Override
  public void startUpdatingLocation() {}

  @Override
  public void stopUpdatingLocation() {}

  @Override
  public void shouldDropEmptyRanges(boolean drop) {}

  /***********************************************************************************************
   * BeaconConsumer
   **********************************************************************************************/
  @Override
  public void onBeaconServiceConnect() {
    Log.v(LOG_TAG, "onBeaconServiceConnect");
    // addXNotifier does not de-duplicate, so remove first (service can reconnect).
    mBeaconManager.removeMonitorNotifier(mMonitorNotifier);
    mBeaconManager.removeRangeNotifier(mRangeNotifier);
    mBeaconManager.addMonitorNotifier(mMonitorNotifier);
    mBeaconManager.addRangeNotifier(mRangeNotifier);
    emitOnBeaconServiceConnected(Arguments.createMap());
  }

  @Override
  public Context getApplicationContext() {
    return mApplicationContext;
  }

  @Override
  public void unbindService(ServiceConnection serviceConnection) {
    mApplicationContext.unbindService(serviceConnection);
  }

  @Override
  public boolean bindService(Intent intent, ServiceConnection serviceConnection, int i) {
    return mApplicationContext.bindService(intent, serviceConnection, i);
  }

  /***********************************************************************************************
   * Monitoring
   **********************************************************************************************/
  @Override
  public void startMonitoringForRegion(ReadableMap regionMap, Promise promise) {
    try {
      Region region = createRegion(regionMap);
      Log.d(LOG_TAG, "startMonitoring: " + region);
      mBeaconManager.startMonitoringBeaconsInRegion(region);
      promise.resolve(null);
    } catch (Exception e) {
      Log.e(LOG_TAG, "startMonitoring, error: ", e);
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  @Override
  public void stopMonitoringForRegion(ReadableMap regionMap, Promise promise) {
    try {
      mBeaconManager.stopMonitoringBeaconsInRegion(createRegion(regionMap));
      promise.resolve(null);
    } catch (Exception e) {
      Log.e(LOG_TAG, "stopMonitoring, error: ", e);
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  @Override
  public void getMonitoredRegions(Promise promise) {
    WritableArray array = Arguments.createArray();
    for (Region region : mBeaconManager.getMonitoredRegions()) {
      array.pushMap(createMonitoringResponse(region));
    }
    promise.resolve(array);
  }

  @Override
  public void requestStateForRegion(ReadableMap regionMap) {
    mBeaconManager.requestStateForRegion(createRegion(regionMap));
  }

  private final MonitorNotifier mMonitorNotifier = new MonitorNotifier() {
    @Override
    public void didEnterRegion(Region region) {
      emitOnRegionDidEnter(createMonitoringResponse(region));
    }

    @Override
    public void didExitRegion(Region region) {
      emitOnRegionDidExit(createMonitoringResponse(region));
    }

    @Override
    public void didDetermineStateForRegion(int i, Region region) {
      String state = "unknown";
      switch (i) {
        case MonitorNotifier.INSIDE:
          state = "inside";
          break;
        case MonitorNotifier.OUTSIDE:
          state = "outside";
          break;
        default:
          break;
      }
      WritableMap map = createMonitoringResponse(region);
      map.putString("state", state);
      emitOnDidDetermineState(map);
    }
  };

  private WritableMap createMonitoringResponse(Region region) {
    WritableMap map = Arguments.createMap();
    map.putString("identifier", region.getUniqueId());
    map.putString("uuid", region.getId1() != null ? region.getId1().toString() : "");
    map.putInt("major", region.getId2() != null ? region.getId2().toInt() : 0);
    map.putInt("minor", region.getId3() != null ? region.getId3().toInt() : 0);
    return map;
  }

  /***********************************************************************************************
   * Ranging
   **********************************************************************************************/
  @Override
  public void startRangingBeaconsInRegion(ReadableMap regionMap, Promise promise) {
    try {
      Region region = createRegion(regionMap);
      Log.d(LOG_TAG, "startRanging: " + region);
      mBeaconManager.startRangingBeaconsInRegion(region);
      promise.resolve(null);
    } catch (Exception e) {
      Log.e(LOG_TAG, "startRanging, error: ", e);
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  @Override
  public void stopRangingBeaconsInRegion(ReadableMap regionMap, Promise promise) {
    try {
      mBeaconManager.stopRangingBeaconsInRegion(createRegion(regionMap));
      promise.resolve(null);
    } catch (Exception e) {
      Log.e(LOG_TAG, "stopRanging, error: ", e);
      promise.reject(E_BEACONS, e.getMessage(), e);
    }
  }

  private final RangeNotifier mRangeNotifier = new RangeNotifier() {
    @Override
    public void didRangeBeaconsInRegion(Collection<Beacon> beacons, Region region) {
      Log.d(LOG_TAG, "didRangeBeaconsInRegion, region: " + region + ", beacons: " + beacons);
      emitOnBeaconsDidRange(createRangingResponse(beacons, region));
    }
  };

  private WritableMap createRangingResponse(Collection<Beacon> beacons, Region region) {
    WritableMap map = Arguments.createMap();
    map.putString("identifier", region.getUniqueId());
    map.putString("uuid", region.getId1() != null ? region.getId1().toString() : "");
    WritableArray a = Arguments.createArray();
    for (Beacon beacon : beacons) {
      WritableMap b = Arguments.createMap();
      b.putString("uuid", beacon.getId1().toString());
      if (beacon.getIdentifiers().size() > 2) {
        b.putInt("major", beacon.getId2().toInt());
        b.putInt("minor", beacon.getId3().toInt());
      }
      b.putInt("rssi", beacon.getRssi());
      double distance = beacon.getDistance();
      if (Double.isInfinite(distance) || Double.isNaN(distance)) {
        b.putDouble("distance", 999.0);
        b.putString("proximity", "far");
      } else {
        b.putDouble("distance", distance);
        b.putString("proximity", getProximity(distance));
      }
      a.pushMap(b);
    }
    map.putArray("beacons", a);
    return map;
  }

  private String getProximity(double distance) {
    if (distance == -1.0) {
      return "unknown";
    } else if (distance < 1) {
      return "immediate";
    } else if (distance < 3) {
      return "near";
    } else {
      return "far";
    }
  }

  /***********************************************************************************************
   * Utils
   **********************************************************************************************/
  private static String optString(ReadableMap map, String key) {
    return map.hasKey(key) && !map.isNull(key) ? map.getString(key) : null;
  }

  private static Identifier optInt(ReadableMap map, String key) {
    return map.hasKey(key) && !map.isNull(key) ? Identifier.fromInt((int) map.getDouble(key)) : null;
  }

  private Region createRegion(ReadableMap map) {
    String uuid = optString(map, "uuid");
    Identifier id1 = (uuid == null || uuid.isEmpty()) ? null : Identifier.parse(uuid);
    return new Region(optString(map, "identifier"), id1, optInt(map, "major"), optInt(map, "minor"));
  }
}
